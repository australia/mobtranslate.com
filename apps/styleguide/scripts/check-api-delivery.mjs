import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const base=process.env.STYLEGUIDE_URL??'http://127.0.0.1:3003';
const index=JSON.parse(await readFile(new URL('../public/api-reference/index.json',import.meta.url),'utf8'));
const results=[];
for(let start=0;start<index.exports.length;start+=3) {
  results.push(...await Promise.all(index.exports.slice(start,start+3).map(async item=>{
    const path=`/api-reference/${encodeURIComponent(item.name)}.json`;
    const response=await fetch(new URL(path,base));
    if(!response.ok)throw new Error(`${item.name}: HTTP ${response.status}`);
    const bytes=await response.text();
    const expected=await readFile(new URL(`../public/api-reference/${item.name}.json`,import.meta.url),'utf8');
    if(bytes!==expected)throw new Error(`${item.name}: served bytes differ from generated reference`);
    const entry=JSON.parse(bytes);
    if(entry.name!==item.name||entry.revision!==index.revision||entry.props.length!==item.props)throw new Error(`${item.name}: index/entry mismatch`);
    return {name:item.name,status:response.status,bytes:Buffer.byteLength(bytes),sha256:createHash('sha256').update(bytes).digest('hex')};
  })));
}
if(process.env.STYLEGUIDE_API_DELIVERY_REPORT)await writeFile(process.env.STYLEGUIDE_API_DELIVERY_REPORT,`${JSON.stringify({base,revision:index.revision,scope:'All generated per-export documents served byte-for-byte by the running preview; not runtime component behavior.',exports:results},null,2)}\n`);
console.log(`${results.length} public export documents served with exact generated bytes and matching revision.`);
